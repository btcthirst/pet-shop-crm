const CYRILLIC_MAP: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "h",
  ґ: "g",
  д: "d",
  е: "e",
  є: "ye",
  ж: "zh",
  з: "z",
  и: "y",
  і: "i",
  ї: "yi",
  й: "y",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "kh",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "shch",
  ь: "",
  ю: "iu",
  я: "ia",
  "'": "",
  "\u2019": "",
};

/** URL-safe slug from a Ukrainian/Latin name: "Корм для собак" → "korm-dla-sobak". */
export function toSlug(input: string): string {
  const transliterated = input
    .trim()
    .toLowerCase()
    .replace(/[а-яіїєґʼ'’]+/g, (chunk) =>
      [...chunk].map((letter) => CYRILLIC_MAP[letter] ?? letter).join(""),
    );
  return transliterated
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
}
